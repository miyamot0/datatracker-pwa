import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { zipSync, type Zippable } from 'fflate';

const SOURCE_DIR = path.resolve('demo-data');
const ARCHIVE_PATH = path.resolve('src/assets/demo/example-data.zip');
const HASH_MODULE_PATH = path.resolve('src/lib/demo-archive-hash.ts');

// Fixed timestamp keeps the archive byte-identical across machines, so the hash only changes with content.
const FIXED_MTIME = new Date(2025, 0, 1);

/**
 * Recursively collects every file under a directory, skipping macOS metadata.
 *
 * @param dir - Directory to walk.
 * @param prefix - Relative path prefix used for archive entry names.
 * @returns Sorted archive entries keyed by forward-slash relative path.
 */
function collectEntries(dir: string, prefix = ''): Zippable {
  const entries: Zippable = {};
  const names = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.name !== '.DS_Store')
    .sort((a, b) => a.name.localeCompare(b.name));

  for (const entry of names) {
    const fullPath = path.join(dir, entry.name);
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;

    if (entry.isDirectory()) {
      Object.assign(entries, collectEntries(fullPath, relative));
    } else if (entry.isFile()) {
      entries[relative] = [new Uint8Array(fs.readFileSync(fullPath)), { mtime: FIXED_MTIME }];
    }
  }

  return entries;
}

const archive = zipSync(collectEntries(SOURCE_DIR), { level: 9 });
const sha256 = createHash('sha256').update(archive).digest('hex');

fs.mkdirSync(path.dirname(ARCHIVE_PATH), { recursive: true });
fs.writeFileSync(ARCHIVE_PATH, archive);

fs.writeFileSync(
  HASH_MODULE_PATH,
  `// Generated by scripts/build-demo-archive.ts. Do not edit by hand.\nexport const DEMO_ARCHIVE_SHA256 = '${sha256}';\n`,
);

console.log(`Wrote ${path.relative(process.cwd(), ARCHIVE_PATH)} (${archive.byteLength} bytes)`);
console.log(`SHA-256 ${sha256}`);
