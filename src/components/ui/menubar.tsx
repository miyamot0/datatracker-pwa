const MENU_SURFACE = '[role="menu"], [role="menubar"] [role="menuitem"][aria-haspopup="menu"]';
const TRIGGER_SELECTOR = '[role="menubar"] [role="menuitem"][aria-haspopup="menu"]';

const isOtherMenubarSurface = (target: EventTarget | null) =>
  target instanceof Element && target.closest(MENU_SURFACE) !== null;

// Only this menu's own trigger should dismiss it. Other triggers switch menus instead, because
// Radix clears the whole menubar value on dismiss and would also close the menu being opened.
const isOtherMenubarTrigger = (target: EventTarget | null, contentId: string) => {
  const trigger = target instanceof Element ? target.closest(TRIGGER_SELECTOR) : null;
  return trigger !== null && trigger.getAttribute('aria-controls') !== contentId;
};

const MenubarContent = React.forwardRef<
  React.ElementRef<typeof MenubarPrimitive.Content>,
  React.ComponentPropsWithoutRef<typeof MenubarPrimitive.Content>
>(
  (
    { className, align = 'start', alignOffset = -4, sideOffset = 8, onPointerDownOutside, onFocusOutside, ...props },
    ref,
  ) => {
    const contentRef = React.useRef<HTMLDivElement | null>(null);
    const setRefs = React.useCallback(
      (node: HTMLDivElement | null) => {
        contentRef.current = node;
        if (typeof ref === 'function') ref(node);
        else if (ref) ref.current = node;
      },
      [ref],
    );
    const contentId = () => contentRef.current?.id ?? '';

    return (
      <MenubarPrimitive.Portal>
        <MenubarPrimitive.Content
          ref={setRefs}
          align={align}
          alignOffset={alignOffset}
          sideOffset={sideOffset}
          onPointerDownOutside={(event) => {
            onPointerDownOutside?.(event);
            if (isOtherMenubarTrigger(event.target, contentId())) event.preventDefault();
          }}
          onFocusOutside={(event) => {
            onFocusOutside?.(event);
            if (isOtherMenubarSurface(event.target)) event.preventDefault();
          }}
          className={cn(
            'z-50 min-w-48 overflow-hidden rounded-md border bg-popover p-1 text-popover-foreground shadow-md data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2',
            className,
          )}
          {...props}
        />
      </MenubarPrimitive.Portal>
    );
  },
);
MenubarContent.displayName = MenubarPrimitive.Content.displayName;

